// Prepares the country borders on the home screen's Quick Challenge art, committed at
// src/data/geo/europe-borders.ts.
//
// Usage: node scripts/prepare-challenge-borders.mjs
//
// Reads the levels' own countries (src/data/geo/europe-west.topo.json, already in the repo: no
// download) and writes the land borders between them as one SVG path, projected like the home
// screen's world map (src/data/geo/world-map.ts: equirectangular, centred on 11°E, 1000 × 500 units),
// so it lies over the world map's painted land without a map library on the page. Only borders
// are drawn (arcs two countries share), never coasts: the art's coasts are the world map's own.
// The data stops at 62°N and 48°E (its clip box), so borders further north or east are not in it;
// the page fades the lines out before that edge. See docs/DATA.md, "Quick Challenge art".
import { geoEquirectangular, geoPath } from "d3-geo";
import { mesh } from "topojson-client";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const input = resolve("src/data/geo/europe-west.topo.json");
const output = resolve("src/data/geo/europe-borders.ts");

// The world map's projection, exactly (scripts/prepare-world-map.mjs): the whole world 1000 units wide,
// its top edge (90°N) at 0.
const WIDTH = 1000;
const projection = geoEquirectangular().rotate([-11, 0]).precision(0.2);
projection.fitWidth(WIDTH, { type: "Sphere" });
const path = geoPath(projection).digits(1);
const [[, top]] = path.bounds({ type: "Sphere" });
projection.translate([projection.translate()[0], projection.translate()[1] - top]);

// Only the borders the art can show (lon −25…48, lat 34…62): the Middle East's and North Africa's
// lie outside it.
const BOX = [-25, 34, 48, 62];
const inBox = ([lon, lat]) => lon >= BOX[0] && lon <= BOX[2] && lat >= BOX[1] && lat <= BOX[3];

const topology = JSON.parse(readFileSync(input, "utf8"));
const borders = mesh(topology, topology.objects.countries, (a, b) => a !== b);

// Each line split where it leaves the box, simplified to within TOLERANCE units of the original
// (Douglas–Peucker; the art draws a unit at about 6px at most, so the lines' detail stays under a
// pixel or two there) and drawn to 0.1 unit. The data's 400 m detail is far finer than the art shows.
const TOLERANCE = 0.12;
const simplify = (points) => {
  if (points.length < 3) return points;
  const [ax, ay] = points[0];
  const [bx, by] = points[points.length - 1];
  const length = Math.hypot(bx - ax, by - ay);
  let [far, index] = [0, 0];
  for (let i = 1; i < points.length - 1; i++) {
    const [px, py] = points[i];
    const distance = length ? Math.abs((bx - ax) * (ay - py) - (ax - px) * (by - ay)) / length : Math.hypot(px - ax, py - ay);
    if (distance > far) [far, index] = [distance, i];
  }
  return far > TOLERANCE ? [...simplify(points.slice(0, index + 1)).slice(0, -1), ...simplify(points.slice(index))] : [points[0], points[points.length - 1]];
};
const lines = [];
for (const line of borders.coordinates) {
  let run = [];
  for (const point of line) {
    if (inBox(point)) run.push(point);
    else {
      if (run.length > 1) lines.push(run);
      run = [];
    }
  }
  if (run.length > 1) lines.push(run);
}
const d = lines
  .map((line) => {
    const points = simplify(line.map(projection)).map((p) => p.map((v) => Math.round(v * 10) / 10));
    const kept = points.filter((p, i) => i === 0 || p[0] !== points[i - 1][0] || p[1] !== points[i - 1][1]);
    return kept.length > 1 ? `M${kept.map((p) => p.join(",")).join("L")}` : "";
  })
  .join("");

const ts = `// Generated by scripts/prepare-challenge-borders.mjs from src/data/geo/europe-west.topo.json (Natural
// Earth Admin 0 – Countries, public domain). Do not edit: see docs/DATA.md, "Quick Challenge art".
// In the world map's units (world-map.ts: equirectangular, centred on 11°E, ${WIDTH} × ${WIDTH / 2}).

/** The land borders between Europe's countries, south of 62°N and west of 48°E, as one SVG path. */
export const EUROPE_BORDERS = ${JSON.stringify(d)};
`;
writeFileSync(output, ts);
console.log(`${output}: ${lines.length} lines, ${(ts.length / 1024).toFixed(1)} KiB`);
